/// Creates an engine with guest debugging instrumentation and epoch
/// interruption, which the debugger needs for breakpoints, stepping and pause.
pub fn debug_engine() -> Result<Engine> {
    let mut config = Config::new();
    config.guest_debug(true);
    config.epoch_interruption(true);
    config.cranelift_opt_level(OptLevel::None);
    Ok(Engine::new(&config)?)
}

/// A compiled module together with its static and debug information.
pub struct Program {
    pub path: PathBuf,
    pub engine: Engine,
    pub module: Module,
    pub info: Arc<WasmModule>,
    pub debug: Option<Arc<DebugInfo>>,
}

impl std::fmt::Debug for Program {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("Program")
            .field("path", &self.path)
            .field("debug", &self.debug.is_some())
            .finish()
    }
}

impl Program {
    /// Reads, parses and compiles a `.wasm` binary or `.wat` text file.
    pub fn load(path: &Path) -> Result<Self> {
        let source = read_module(path)?;
        Self::from_parts(path, source.bytes, source.dwarf_bias)
    }

    pub fn from_bytes(path: &Path, bytes: Vec<u8>) -> Result<Self> {
        Self::from_parts(path, bytes, 0)
    }

    fn from_parts(path: &Path, bytes: Vec<u8>, dwarf_bias: u32) -> Result<Self> {
        let info = Arc::new(WasmModule::parse(bytes)?);
        let debug = match DebugInfo::load_with_bias(info.bytes(), dwarf_bias) {
            Ok(debug) => debug.map(Arc::new),
            Err(e) => {
                tracing::warn!("ignoring unreadable DWARF in {}: {e}", path.display());
                None
            }
        };
        let engine = debug_engine()?;
        let module = Module::new(&engine, info.bytes())
            .map_err(|e| Error::InvalidModule(crate::error::format_runtime_error(&e)))?;
        Ok(Self {
            path: path.to_path_buf(),
            engine,
            module,
            info,
            debug,
        })
    }
}

/// A module binary and the bias to apply to its DWARF code addresses.
pub struct ModuleSource {
    pub bytes: Vec<u8>,
    pub dwarf_bias: u32,
}

/// Reads a module from disk, translating WebAssembly text (with generated
/// DWARF pointing back at the text file) when the file is not a binary.
pub fn read_module(path: &Path) -> Result<ModuleSource> {
    let bytes = std::fs::read(path)
        .map_err(|e| Error::Config(format!("cannot read {}: {e}", path.display())))?;
    if bytes.starts_with(b"\0asm") {
        return Ok(ModuleSource {
            bytes,
            dwarf_bias: 0,
        });
    }
    let absolute = std::path::absolute(path).unwrap_or_else(|_| path.to_path_buf());
    let bytes = wat::Parser::new()
        .generate_dwarf(wat::GenerateDwarf::Full)
        .parse_file(&absolute)
        .map_err(|e| Error::InvalidModule(e.to_string()))?;
    let dwarf_bias = text_dwarf_bias(&bytes);
    Ok(ModuleSource { bytes, dwarf_bias })
}

/// DWARF generated by the `wat` crate addresses code relative to the first
/// function entry instead of the start of the code section payload, so its
/// addresses are short by the length of the function-count LEB128.
fn text_dwarf_bias(wasm: &[u8]) -> u32 {
    for payload in wasmparser::Parser::new(0).parse_all(wasm) {
        if let Ok(wasmparser::Payload::CodeSectionStart { count, .. }) = payload {
            let mut value = count;
            let mut length = 1;
            while value >= 0x80 {
                value >>= 7;
                length += 1;
            }
            return length;
        }
    }
    0
}

struct ThreadWaker(std::thread::Thread);

impl Wake for ThreadWaker {
    fn wake(self: Arc<Self>) {
        self.0.unpark();
    }
}

/// Drives a future to completion on the current thread.
///
/// Wasmtime requires async entry points once a debug handler is installed;
/// the handler itself blocks the thread while the debuggee is paused, so a
/// minimal parking executor is sufficient and keeps nested calls possible.
pub fn block_on<F: Future>(future: F) -> F::Output {
    let mut future = pin!(future);
    let waker = Waker::from(Arc::new(ThreadWaker(std::thread::current())));
    let mut cx = Context::from_waker(&waker);
    loop {
        match future.as_mut().poll(&mut cx) {
            Poll::Ready(value) => return value,
            Poll::Pending => std::thread::park(),
        }
    }
}
